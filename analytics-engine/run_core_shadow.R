#!/usr/bin/env Rscript
# Private child protocol. No CLI JSON is an authority without the inherited secret.
args <- commandArgs(trailingOnly=TRUE)
if (length(args)!=2L) stop('Expected request and new output paths')
if (getRversion() < '4.5.1') stop('R 4.5.1+ required')
if (!requireNamespace('digest',quietly=TRUE) || !requireNamespace('jsonlite',quietly=TRUE)) stop('digest and jsonlite required')
key <- Sys.getenv('FISCALSTUDY_SHADOW_SECRET',unset='')
expected <- Sys.getenv('FISCALSTUDY_SHADOW_REQUEST_MAC',unset='')
if (!grepl('^[0-9a-f]{64}$',key) || !grepl('^[0-9a-f]{64}$',expected)) stop('UNAUTHENTICATED_HOST')
size <- file.info(args[1])$size
if (is.na(size) || size<1 || size>32*1024^2) stop('Invalid request size')
bytes <- readBin(args[1],'raw',n=size)
if (!identical(digest::hmac(key,bytes,algo='sha256',serialize=FALSE),expected)) stop('HOST_AUTHENTICATION_FAILED')
request <- jsonlite::fromJSON(rawToChar(bytes),simplifyVector=FALSE)
source('R/provenance.R'); source('R/learning_profile.R'); source('R/evidence_specialists.R')
source('lab/decision_scientific_evaluation.R'); source('R/core_shadow_adapter.R')
files <- core_shadow_source_files()
if (!setequal(names(request$engine_sources),files) || !all(vapply(files,function(f)
  identical(request$engine_sources[[f]],compute_file_sha256(f)),logical(1)))) stop('ENGINE_SOURCE_VERSION_MISMATCH')
payload <- core_shadow_decision(request)
output <- charToRaw(enc2utf8(jsonlite::toJSON(payload,auto_unbox=TRUE,null='null',na='null',digits=16,dataframe='rows')))
if (file.exists(args[2]) || file.exists(paste0(args[2],'.mac'))) stop('Refusing overwrite')
con <- file(args[2],open='wxb'); writeBin(output,con); close(con)
writeLines(digest::hmac(key,output,algo='sha256',serialize=FALSE),paste0(args[2],'.mac'),useBytes=TRUE)
Sys.unsetenv(c('FISCALSTUDY_SHADOW_SECRET','FISCALSTUDY_SHADOW_REQUEST_MAC'))
cat('Observation-only shadow complete\n')
