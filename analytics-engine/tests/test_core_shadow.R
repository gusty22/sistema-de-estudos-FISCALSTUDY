# Exercise the real private-process boundary. Secret is ephemeral, not an operational key.
cs_dir <- tempfile('core-shadow-test-'); dir.create(cs_dir)
cs_request <- file.path(cs_dir,'request.json'); cs_output <- file.path(cs_dir,'output.json')
cs_bytes <- charToRaw(enc2utf8(jsonlite::toJSON(cs_input,auto_unbox=TRUE,null='null',digits=16)))
writeBin(cs_bytes,cs_request)
cs_key <- paste(rep('ab',32),collapse='')
cs_old <- Sys.getenv(c('FISCALSTUDY_SHADOW_SECRET','FISCALSTUDY_SHADOW_REQUEST_MAC'),unset=NA_character_)
Sys.unsetenv(c('FISCALSTUDY_SHADOW_SECRET','FISCALSTUDY_SHADOW_REQUEST_MAC'))
cs_cli <- function() suppressWarnings(system2(file.path(R.home('bin'),'Rscript'),
  c('--vanilla','run_core_shadow.R',shQuote(cs_request),shQuote(cs_output)),stdout=FALSE,stderr=FALSE))
assert_true(cs_cli()!=0L,'Unauthenticated JSON cannot become host authority')
Sys.setenv(FISCALSTUDY_SHADOW_SECRET=cs_key,FISCALSTUDY_SHADOW_REQUEST_MAC=paste(rep('0',64),collapse=''))
assert_true(cs_cli()!=0L,'Self-declared origin plus invalid MAC cannot become authority')
Sys.setenv(FISCALSTUDY_SHADOW_REQUEST_MAC=digest::hmac(cs_key,cs_bytes,algo='sha256',serialize=FALSE))
assert_equal(cs_cli(),0L,'Authenticated private host process produces decision and lab record')
cs_out <- readBin(cs_output,'raw',n=file.info(cs_output)$size)
assert_equal(trimws(readLines(paste0(cs_output,'.mac'))),digest::hmac(cs_key,cs_out,algo='sha256',serialize=FALSE),'Child MAC binds exact output bytes')
cs_imported <- jsonlite::fromJSON(rawToChar(cs_out),simplifyVector=FALSE)
assert_equal(.se_hash(.se_replay_policy(cs_imported$scientific_record)),.se_hash(cs_imported$result),'Persisted JSON scientific record replays through original evaluator')
assert_equal(.se_hash(evaluate_scientific_decisions(cs_imported$scientific_input)),.se_hash(cs_imported$scientific_report),'Persisted JSON is consumed by existing scientific lab')
unlink(c(cs_output,paste0(cs_output,'.mac')))
cs_forged <- cs_input; cs_forged$candidates[[1]]$candidate_id <- 'external-fake-inventory'
cs_forged$can_apply <- TRUE; cs_forged$origin <- 'REAL_STUDY'
cs_forged_bytes <- charToRaw(jsonlite::toJSON(cs_forged,auto_unbox=TRUE,null='null',digits=16))
writeBin(cs_forged_bytes,cs_request)
assert_true(cs_cli()!=0L,'Altered inventory and permission flags cannot reuse an authenticated request MAC')
assert_false(file.exists(cs_output),'Failed ingress authentication produces no decision artifact')
cs_stale <- cs_input; cs_stale$engine_sources[['R/learning_profile.R']] <- paste(rep('0',64),collapse='')
cs_stale_bytes <- charToRaw(jsonlite::toJSON(cs_stale,auto_unbox=TRUE,null='null',digits=16))
writeBin(cs_stale_bytes,cs_request)
Sys.setenv(FISCALSTUDY_SHADOW_REQUEST_MAC=digest::hmac(cs_key,cs_stale_bytes,algo='sha256',serialize=FALSE))
assert_true(cs_cli()!=0L,'Authenticated snapshot rejects incompatible transitive dependency version')
for (i in seq_along(cs_old)) if(is.na(cs_old[i])) Sys.unsetenv(names(cs_old)[i]) else do.call(Sys.setenv,setNames(list(cs_old[i]),names(cs_old)[i]))
unlink(cs_dir,recursive=TRUE)
